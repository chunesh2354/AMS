/** Section 3, principle 10: an empty list says one sentence and offers one primary action. */
test.describe('empty states', () => {
  for (const path of [...FIRM_LISTS, ...TEAM_LISTS].filter((p) => !p.includes('/firm/overview'))) {
    test(path, async ({ page }) => {
      await page.goto(withDemo(path, 'empty'));
      await page.getByLabel('Loading').first().waitFor({ state: 'detached', timeout: 5000 }).catch(() => {});
      const states = page.locator('.state').filter({ hasNotText: 'Select an item to preview it.' });
      await expect(states.first()).toBeVisible();
      for (const s of await states.all()) {
        const text = (await s.locator('.state__body').innerText()).trim();
        expect(text.split(/[.!?](\s|$)/).filter((x) => x.trim()).length, text).toBe(1);
        expect(await s.locator('button, a').count(), text).toBe(1);
      }
    });
  }
});

test('glass falls back to surface with no layout shift when backdrop-filter is off', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/firm/overview');
  await page.evaluate(() => document.fonts.ready);
  const boxes = () => page.evaluate(() => Array.from(document.querySelectorAll('.glass')).map((el) => { const r = el.getBoundingClientRect(); return [r.x, r.y, r.width, r.height]; }));
  const before = await boxes();
  await page.addStyleTag({ content: '.glass { background: var(--surface) !important; -webkit-backdrop-filter: none !important; backdrop-filter: none !important; }' });
  expect(await boxes()).toEqual(before);
  const bg = await page.locator('.kpi.glass').first().evaluate((el) => getComputedStyle(el).backgroundColor);
  const surface = await page.evaluate(() => { const d = document.createElement('div'); d.style.background = 'var(--surface)'; document.body.append(d); const c = getComputedStyle(d).backgroundColor; d.remove(); return c; });
  expect(bg).toBe(surface);
});
