import { expect, test } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import { FIRM_LISTS, TEAM_LISTS, withDemo } from './routes';

const report: string[] = [];
const docs = (name: string) => fileURLToPath(new URL(`../../../docs/${name}`, import.meta.url));

/**
 * The alignment audit from U-20. Every block on the page starts at the gutter or is deliberately full-bleed, and the
 * vertical gap between blocks stays on the 4 px half-step of the 8 px baseline.
 */
test.describe('alignment', () => {
  for (const path of [...FIRM_LISTS, ...TEAM_LISTS]) {
    test(path, async ({ page }) => {
      await page.setViewportSize({ width: 1440, height: 900 });
      await page.goto(path);
      await page.evaluate(() => document.fonts.ready);
      await page.getByLabel('Loading').first().waitFor({ state: 'detached', timeout: 5000 }).catch(() => {});
      await page.waitForTimeout(50);
      const blocks = await page.evaluate(() => {
        const root = document.querySelector('.shell__content')!;
        const content = root.getBoundingClientRect();
        const style = getComputedStyle(root);
        const gutter = parseFloat(style.paddingLeft);
        return {
          left: content.left + gutter,
          right: content.right - gutter,
          contentLeft: content.left,
          items: Array.from(root.children).map((el) => {
            const r = el.getBoundingClientRect();
            return { cls: el.className || el.tagName, left: r.left, right: r.right, top: r.top, bottom: r.bottom, h: r.height };
          }).filter((b) => b.h > 1),
        };
      });
      const off: string[] = [];
      for (const b of blocks.items) {
        const atGutter = Math.abs(b.left - blocks.left) < 0.6 && b.right <= blocks.right + 0.6;
        const bleed = Math.abs(b.left - blocks.contentLeft) < 0.6;
        if (!atGutter && !bleed) off.push(`${b.cls}: left ${b.left}, right ${b.right}`);
      }
      for (let i = 1; i < blocks.items.length; i += 1) {
        const gap = blocks.items[i].top - blocks.items[i - 1].bottom;
        if (Math.abs(gap / 4 - Math.round(gap / 4)) > 0.13) off.push(`gap ${gap} before ${blocks.items[i].cls}`);
      }
      report.push(`| ${path} | ${blocks.items.length} | ${off.length ? off.join('; ') : 'OK'} |`);
      expect(off).toEqual([]);
    });
  }
  test.afterAll(() => {
    if (!report.length) return;
    report.sort();
    fs.writeFileSync(docs('ui-alignment.md'), ['# Alignment audit', '', 'Generated by `tests/audit.spec.ts` at 1440 px: blocks start at the gutter or are deliberately full-bleed, and vertical gaps sit on the 4 px half-step of the 8 px baseline. Grid-overlay screenshots are `docs/ui-screens/audit-grid-*.png`.', '', '| Route | Blocks | Result |', '| --- | --- | --- |', ...report, ''].join('\n'));
  });
});

