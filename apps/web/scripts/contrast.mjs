// WCAG contrast report. Reads every colour token from tokens.css, composites each glass
// and soft surface over BOTH gradient extremes and checks the text that can sit on it.
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync(new URL('../src/ui/tokens.css', import.meta.url), 'utf8');
const block = (re) => Object.fromEntries([...css.match(re)[1].matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const light = block(/\/\* LIGHT \*\/([\s\S]*?)\/\* END LIGHT \*\//);
const dark = { ...light, ...block(/\/\* DARK \*\/([\s\S]*?)\/\* END DARK \*\//) };

const parse = (s) => {
  let m = s.match(/^#([0-9a-f]{6})$/i);
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)).concat(1);
  m = s.match(/^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/);
  if (m) return [+m[1], +m[2], +m[3], +m[4]];
  throw new Error('cannot parse ' + s);
};
const over = (f, b) => [0, 1, 2].map((i) => f[i] * f[3] + b[i] * (1 - f[3])).concat(1);
const lum = ([r, g, b]) => {
  const c = [r, g, b].map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const planes = { light: ['#e8eef7', '#f4f6f9', '#eef1f5'], dark: ['#1b2230', '#0f141c', '#0b0f15'] };
const rows = [];
let fails = 0;
for (const [mode, t] of [['light', light], ['dark', dark]]) {
  const bases = { surface: [parse(t.surface)], 'surface-muted': [parse(t['surface-muted'])], 'surface-raised': [parse(t['surface-raised'])] };
  for (const g of ['glass-1', 'glass-2']) bases[g] = planes[mode].map((p) => over(parse(t[g]), parse(p)));
  const check = (fg, bg, need, solid) => {
    for (const b of bases[bg]) {
      const back = solid ? over(parse(t[solid]), b) : b;
      const r = ratio(parse(t[fg]), back);
      if (r < need) fails++;
      rows.push({ mode, fg, bg: solid ? `${solid} on ${bg}` : bg, ratio: +r.toFixed(2), need, pass: r >= need });
    }
  };
  for (const bg of Object.keys(bases)) {
    for (const fg of ['ink-1', 'ink-2', 'accent-text']) check(fg, bg, 4.5);
    for (const tone of ['ok', 'warn', 'danger', 'info', 'neutral']) {
      check(`${tone}-ink`, bg, 4.5);
      check(`${tone}-ink`, bg, 4.5, `${tone}-soft`);
    }
    check('ink-1', bg, 4.5, 'accent-soft');
  }
  const accent = parse(t.accent);
  const r = ratio(parse(t['accent-ink']), accent);
  if (r < 4.5) fails++;
  rows.push({ mode, fg: 'accent-ink', bg: 'accent', ratio: +r.toFixed(2), need: 4.5, pass: r >= 4.5 });
}
const worst = new Map();
for (const r of rows) { const k = `${r.mode}|${r.fg}|${r.bg}`; if (!worst.has(k) || r.ratio < worst.get(k).ratio) worst.set(k, r); }
const list = [...worst.values()];
const md = ['# Contrast report', '', 'Generated by `npm run contrast`. Worst case across all gradient stops of `--bg-plane`.', '', '| Mode | Text | On | Ratio | Needs | Pass |', '| --- | --- | --- | --- | --- | --- |',
  ...list.map((r) => `| ${r.mode} | \`--${r.fg}\` | \`--${r.bg}\` | ${r.ratio.toFixed(2)} | ${r.need} | ${r.pass ? 'yes' : 'NO'} |`)].join('\n');
writeFileSync(new URL('../../../docs/ui-contrast.md', import.meta.url), md + '\n');
for (const r of list.filter((x) => !x.pass)) console.log('FAIL', r.mode, r.fg, 'on', r.bg, r.ratio);
console.log(`${list.length} pairs, ${list.filter((r) => !r.pass).length} failures`);
process.exit(fails ? 1 : 0);
